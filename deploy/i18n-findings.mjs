#!/usr/bin/env node
/**
 * Regenerate site/src/lib/findings-fr.ts.
 *
 * The findings page quotes headlines verbatim from findings.json, the artifact
 * the pilot scripts write. Their French translations are hand-written and so
 * can go stale when the pipeline regenerates the artifact. This script binds
 * each translation to the EXACT English text it translates:
 *
 *   node deploy/i18n-findings.mjs
 *
 * reads  <app>/src/data/findings.json            (the artifact)
 *        <app>/src/lib/findings-fr.translations.json  (the hand-written French)
 * writes <app>/src/lib/findings-fr.ts
 *
 * At render time frFinding() returns the French only while the recorded source
 * still matches the artifact, so a regenerated headline makes the French page
 * fall back to the verbatim English for that finding instead of silently
 * serving a stale translation. After re-translating, run this again.
 *
 * The app directory is located by its .metacan-app marker, like deploy.sh, so
 * the coming repository reorganization cannot break this script.
 */

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const repoRoot = execSync('git rev-parse --show-toplevel', { encoding: 'utf8' }).trim()
const markers = execSync('git ls-files', { cwd: repoRoot, encoding: 'utf8' })
  .split('\n')
  .filter((f) => /(^|\/)\.metacan-app$/.test(f))
if (markers.length !== 1) {
  console.error(`expected exactly one tracked .metacan-app marker, found ${markers.length}`)
  process.exit(1)
}
const app = join(repoRoot, dirname(markers[0]))

const findings = JSON.parse(readFileSync(join(app, 'src/data/findings.json'), 'utf8'))
const fr = JSON.parse(readFileSync(join(app, 'src/lib/findings-fr.translations.json'), 'utf8'))

const keys = Object.keys(findings).sort()
const missing = keys.filter((k) => !(k in fr))
const extra = Object.keys(fr).filter((k) => !(k in findings))
if (missing.length || extra.length) {
  console.error('translations out of step with findings.json', { missing, extra })
  process.exit(1)
}

let out = `import findings from '@/data/findings.json'

/**
 * French translations of the ${keys.length} finding headlines.
 *
 * The headlines are quoted artifacts: findings.json is written by the pilot
 * scripts, and the findings page's whole claim is that no number on it was
 * typed by a human. A hand-written translation reintroduces exactly that risk,
 * so every entry here records the EXACT English source it translates, and
 * frFinding() returns the French only while the artifact still matches.
 * If the pipeline regenerates a headline, the French page falls back to the
 * verbatim English for that finding (correct and loud) instead of silently
 * serving a stale translation (fluent and wrong). Re-translate, update the
 * source string, and the French comes back.
 *
 * This file is generated by deploy/i18n-findings.mjs from findings.json plus
 * the hand-written translations; regenerate it rather than editing sources by
 * hand.
 */

interface FrFinding {
  /** The exact English headline this translates, byte for byte. */
  source: string
  fr: string
}

export const FR_FINDINGS: Record<string, FrFinding> = {
`
for (const k of keys) {
  out += `  ${k}: {\n    source:\n      ${JSON.stringify(findings[k].headline)},\n    fr:\n      ${JSON.stringify(fr[k])},\n  },\n`
}
out += `}

/**
 * The French headline for a finding, or null when there is no translation
 * whose recorded source matches the current artifact text.
 */
export function frFinding(key: string, currentHeadline: string): string | null {
  const entry = FR_FINDINGS[key]
  if (!entry) return null
  return entry.source === currentHeadline ? entry.fr : null
}
`
writeFileSync(join(app, 'src/lib/findings-fr.ts'), out)
console.log(`findings-fr.ts regenerated: ${keys.length} findings`)

// The one honesty check a generator can make: every translation still matches
// a live artifact entry, so none of them can be stale at generation time.
